def patch_cells(cells):
    for index, old, new, why in CELL_PATCHES:
        source = "".join(cells[index]["source"])
        count = source.count(old)
        if count != 1:
            raise SystemExit(
                f"[make] patch failed ({why}): cell {index} has {count} matches for {old!r}"
            )
        cells[index]["source"] = as_source(source.replace(old, new, 1))


def build_notebook():
    with open(SRC_NB, encoding="utf-8") as handle:
        notebook = json.load(handle)
    cells = notebook["cells"][:9]
    patch_cells(cells)
    cells[0] = md(MD_HEAD)
    cells += [
        md(MD_PLAN),
        code(CODE_DRIVER),
        md(MD_SMOKE),
        code(CODE_SMOKE),
        md(MD_DRIVER),
        code(CODE_RUN),
        md(MD_ZIP),
        code(CODE_ZIP),
        md(MD_GATE),
        code(CODE_GATE),
    ]
    notebook["cells"] = cells
    return notebook


def write_notebook(path=OUT_NB):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(build_notebook(), handle, ensure_ascii=False, indent=1)
        handle.write("\n")
    return path


